export function buildTenantPolicy(template: PolicyTemplate, tenantId: string, status: TenantPolicy["status"] = "Active"): TenantPolicy {
  const now = new Date().toISOString();

  return {
    ...template,
    id: `${tenantId}-${template.id}`,
    tenantId,
    status,
    source: "standard",
    createdAt: now,
    updatedAt: now,
  };
}

export function getPolicyTemplate(templateId: string) {
  return policyTemplates.find((template) => template.id === templateId) ?? null;
}
