export type PolicyCategory = "Baseline" | "AgentShield Signature" | "Custom Library";
export type PolicyDecision = "Allow" | "Challenge" | "Deny" | "Monitor" | "Quarantine";
export type PolicyEnforcementMode = "Monitor" | "Challenge" | "Block" | "Quarantine";

export type PolicyTemplate = {
  id: string;
  name: string;
  category: PolicyCategory;
  pack: string;
  decision: PolicyDecision;
  enforcementMode: PolicyEnforcementMode;
  riskTier: "Low" | "Medium" | "High" | "Critical";
  rule: string;
  businessValue: string;
  configuration: string[];
  evidence: string[];
  frameworks: string[];
};

export type TenantPolicy = PolicyTemplate & {
  tenantId: string;
  status: "Available" | "Active" | "Draft";
  source: "standard" | "cloned";
  createdAt: string;
  updatedAt: string;
};

